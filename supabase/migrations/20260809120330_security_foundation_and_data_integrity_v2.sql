create or replace function public.normalize_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if (select auth.uid()) = new.id then
    new.email := null;
    new.ratings_count := 0;
    new.avg_rating := 0;
    new.streak := 0;
    new.streak_date := null;
    new.is_admin := false;
  end if;
  if new.invite_code is null or btrim(new.invite_code) = '' then
    loop
      new.invite_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
      exit when not exists (select 1 from public.users where invite_code = new.invite_code);
    end loop;
  end if;
  return new;
end
$function$;

create or replace function public.protect_user_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if (select auth.uid()) = old.id
    and current_setting('app.allow_managed_profile_update', true) is distinct from 'true'
    and (
      new.id is distinct from old.id or new.email is distinct from old.email
      or new.invite_code is distinct from old.invite_code
      or new.ratings_count is distinct from old.ratings_count
      or new.avg_rating is distinct from old.avg_rating
      or new.streak is distinct from old.streak
      or new.streak_date is distinct from old.streak_date
      or new.is_admin is distinct from old.is_admin
      or new.created_at is distinct from old.created_at
    )
  then
    raise exception 'This profile field is managed by FOOTBAZED.';
  end if;
  return new;
end
$function$;

create or replace function public.refresh_user_rating_stats()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  target_user uuid := coalesce(new.user_id, old.user_id);
begin
  perform set_config('app.allow_managed_profile_update', 'true', true);
  update public.users
  set ratings_count = (select count(*) from public.ratings where user_id = target_user),
      avg_rating = coalesce((select round(avg(match_rating)::numeric, 1) from public.ratings where user_id = target_user), 0)
  where id = target_user;
  return coalesce(new, old);
end
$function$;

create or replace function public.record_rating_streak()
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_user_id uuid := (select auth.uid());
  previous_day date;
begin
  if current_user_id is null then raise exception 'Authentication is required.'; end if;
  select u.streak_date into previous_day from public.users u where u.id = current_user_id for update;
  if previous_day = current_date then return; end if;
  perform set_config('app.allow_managed_profile_update', 'true', true);
  update public.users
  set streak = case when previous_day = current_date - 1 then coalesce(streak, 0) + 1 else 1 end,
      streak_date = current_date
  where id = current_user_id;
end
$function$;

create or replace function public.get_my_profile()
returns setof public.users
language sql
stable
security definer
set search_path = ''
as $function$
  select u.* from public.users u where u.id = (select auth.uid());
$function$;

create or replace function public.resolve_invite_code(lookup_code text)
returns table (
  id uuid, username text, display_name text, avatar_url text, bio text,
  favorite_teams text, ratings_count integer, avg_rating numeric, streak integer,
  is_public boolean
)
language sql
stable
security definer
set search_path = ''
as $function$
  select u.id, u.username, u.display_name, u.avatar_url, u.bio,
         u.favorite_teams, u.ratings_count, u.avg_rating, u.streak, u.is_public
  from public.users u
  where upper(u.invite_code) = upper(btrim(lookup_code))
    and u.id <> (select auth.uid())
  limit 1;
$function$;

