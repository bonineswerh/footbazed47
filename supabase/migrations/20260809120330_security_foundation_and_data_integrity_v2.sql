create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  league_name text not null,
  home_team_name text not null,
  away_team_name text not null,
  match_date timestamptz not null,
  status text default 'scheduled' check (status = any (array['scheduled', 'live', 'finished', 'postponed', 'cancelled'])),
  home_score smallint check (home_score is null or home_score >= 0),
  away_score smallint check (away_score is null or away_score >= 0),
  external_id bigint unique,
  league_code text,
  matchday integer,
  season text,
  api_fixture_id integer
);

create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  team text not null,
  position text,
  photo_url text,
  created_at timestamp default now(),
  shirt_number integer,
  unique (name, team)
);

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  email text,
  avatar_url text,
  bio text,
  favorite_teams text,
  invite_code text unique,
  ratings_count integer default 0,
  avg_rating numeric default 0,
  streak integer default 0,
  streak_date date,
  is_public boolean default true,
  created_at timestamptz default now(),
  last_seen timestamptz default now(),
